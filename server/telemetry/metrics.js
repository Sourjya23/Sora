const client = require("prom-client");

// Enable collection of default metrics (CPU, Memory, Event Loop Lag, GC)
const register = new client.Registry();
client.collectDefaultMetrics({ register, prefix: "sora_" });

// Custom Business Metrics for Sora & Cloud Agents
const outboxQueueGauge = new client.Gauge({
  name: "sora_outbox_unpublished_events",
  help: "Number of unpublished events in the transactional outbox",
  registers: [register],
});

const emailJobsCounter = new client.Counter({
  name: "sora_email_jobs_total",
  help: "Total email jobs processed by Central Email Orchestrator",
  labelNames: ["template", "status"],
  registers: [register],
});

const activeSocketGauge = new client.Gauge({
  name: "sora_active_socket_connections",
  help: "Current active Socket.io connections in meeting rooms",
  registers: [register],
});

const forensicFindingsCounter = new client.Counter({
  name: "sora_forensic_findings_total",
  help: "Total granular forensic findings generated by AI Forensic Agent",
  labelNames: ["category", "severity"],
  registers: [register],
});

const sentinelAuditCounter = new client.Counter({
  name: "sora_sentinel_audits_total",
  help: "Total reconciliation audits executed by Sentinel Supervisor",
  labelNames: ["status"],
  registers: [register],
});

module.exports = {
  register,
  outboxQueueGauge,
  emailJobsCounter,
  activeSocketGauge,
  forensicFindingsCounter,
  sentinelAuditCounter,
};
